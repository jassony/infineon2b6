function add_from_workspace(modelName, sourceLibrary, blockName, variableName, position)
add_block(sourceLibrary, [modelName '/' blockName], ...
    'VariableName', variableName, ...
    'Interpolate', 'off', ...
    'OutputAfterFinalValue', 'Holding final value', ...
    'Position', position);
end

function add_to_workspace(modelName, blockName, variableName, position)
add_block('simulink/Sinks/To Workspace', [modelName '/' blockName], ...
    'VariableName', variableName, ...
    'SaveFormat', 'Timeseries', ...
    'MaxDataPoints', 'inf', ...
    'Position', position);
end

function add_data_type_conversion(modelName, blockName, outputType, position)
add_block('simulink/Signal Attributes/Data Type Conversion', ...
    [modelName '/' blockName], ...
    'OutDataTypeStr', outputType, ...
    'Position', position);
end

function add_named_line(modelName, source, destination, signalName)
lineHandle = add_line(modelName, source, destination, 'autorouting', 'on');
set_param(lineHandle, 'Name', signalName);
end

function configure_kre_observer_chart(modelName)
root = sfroot;
chart = root.find('-isa', 'Stateflow.EMChart', ...
    'Path', [modelName '/KREObserver']);
if isempty(chart)
    error('build_kre_ekf_validation_model:MissingKreFunctionBlock', ...
        'Could not locate the KREObserver MATLAB Function block.');
end

chart = chart(1);
chart.Script = sprintf([ ...
    'function [active_flux_alpha_wb, active_flux_beta_wb, kre_status] = ...\n' ...
    '    KREObserver(kre_enable, kre_vi_fb, kre_params, kre_reset, kre_pll_params)\n' ...
    '%%#codegen\n' ...
    'persistent state\n' ...
    'if isempty(state)\n' ...
    '    state = zeros(18, 1, ''single'');\n' ...
    'end\n' ...
    '[state, active_flux_alpha_wb, active_flux_beta_wb, kre_status] = ...\n' ...
    '    kre_ekf_kre_step(state, kre_enable, kre_vi_fb, kre_params, ...\n' ...
    '    kre_reset, kre_pll_params);\n' ...
    'end\n']);
end

function configure_estimator_chart(modelName)
root = sfroot;
chart = root.find('-isa', 'Stateflow.EMChart', ...
    'Path', [modelName '/FluxEKF']);
if isempty(chart)
    error('build_kre_ekf_validation_model:MissingFunctionBlock', ...
        'Could not locate the FluxEKF MATLAB Function block.');
end

chart = chart(1);
chart.Script = sprintf([ ...
    'function [positionPU, speedPU, fluxCos, fluxSin, fluxValid] = ...\n' ...
    '    FluxEKF(activeFluxAlphaWb, activeFluxBetaWb, kreStatus, reset)\n' ...
    '%%#codegen\n' ...
    'persistent state initialized positionHold speedHold\n' ...
    'if isempty(state)\n' ...
    '    state = zeros(3, 1);\n' ...
    '    initialized = false;\n' ...
    '    positionHold = 0;\n' ...
    '    speedHold = 0;\n' ...
    'end\n' ...
    'fluxCos = 0;\n' ...
    'fluxSin = 0;\n' ...
    'fluxValid = uint8(0);\n' ...
    'if reset ~= 0\n' ...
    '    state = zeros(3, 1);\n' ...
    '    initialized = false;\n' ...
    '    positionHold = 0;\n' ...
    '    speedHold = 0;\n' ...
    'end\n' ...
    'if kreStatus == uint8(1)\n' ...
    '    fluxAlpha = double(activeFluxAlphaWb);\n' ...
    '    fluxBeta = double(activeFluxBetaWb);\n' ...
    '    fluxMagnitude = sqrt(fluxAlpha * fluxAlpha + fluxBeta * fluxBeta);\n' ...
    '    if isfinite(fluxMagnitude) && fluxMagnitude > 0\n' ...
    '        fluxCos = fluxAlpha / fluxMagnitude;\n' ...
    '        fluxSin = fluxBeta / fluxMagnitude;\n' ...
    '        [state, positionHold, speedHold] = resolver_ekf_step( ...\n' ...
    '            state, fluxCos, fluxSin, ~initialized, resolver_ekf_config);\n' ...
    '        initialized = true;\n' ...
    '        fluxValid = uint8(1);\n' ...
    '    end\n' ...
    'end\n' ...
    'positionPU = positionHold;\n' ...
    'speedPU = speedHold;\n' ...
    'end\n']);

configData = Stateflow.Data(chart);
configData.Name = 'resolver_ekf_config';
configData.Scope = 'Parameter';
configData.DataType = 'Inherit: Same as Simulink';
end
