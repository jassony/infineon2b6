function modelPath = build_kre_ekf_validation_model(options)
%BUILD_KRE_EKF_VALIDATION_MODEL Build the KRE-to-resolver-EKF harness.
%   The model is intentionally independent from the FOC, FADO, and legacy
%   KRE observer paths. KRE provides active-flux alpha/beta components;
%   FluxEKF normalizes only valid flux vectors and estimates electrical
%   position and speed using resolver_ekf_step.

arguments
    options.ForceRebuild (1, 1) logical = true
end

modelName = 'kre_ekf_validation';
modelDirectory = fileparts(mfilename('fullpath'));
resolverEkfDirectory = fullfile(fileparts(modelDirectory), 'resolver_ekf');
modelPath = fullfile(modelDirectory, [modelName '.slx']);

validate_dependencies(modelDirectory, resolverEkfDirectory);
addpath(modelDirectory);
addpath(resolverEkfDirectory);
configure_file_generation_folders(modelDirectory, modelName);

if bdIsLoaded(modelName)
    close_system(modelName, 0);
end

if ~options.ForceRebuild && isfile(modelPath)
    return
end

if isfile(modelPath)
    delete(modelPath);
end

new_system(modelName);
load_system(modelName);

try
    configure_model(modelName);
    add_validation_blocks(modelName);
    save_system(modelName, modelPath);
catch exception
    if bdIsLoaded(modelName)
        close_system(modelName, 0);
    end
    rethrow(exception);
end

close_system(modelName, 0);
end

function validate_dependencies(modelDirectory, resolverEkfDirectory)
kreStepPath = fullfile(modelDirectory, 'kre_ekf_kre_step.m');
if ~isfile(kreStepPath)
    error('build_kre_ekf_validation_model:MissingKreStep', ...
        'Missing local KRE step function: %s', kreStepPath);
end

if ~isfolder(resolverEkfDirectory)
    error('build_kre_ekf_validation_model:MissingResolverEkfDirectory', ...
        'Missing resolver EKF directory: %s', resolverEkfDirectory);
end

resolverStepPath = fullfile(resolverEkfDirectory, 'resolver_ekf_step.m');
if ~isfile(resolverStepPath)
    error('build_kre_ekf_validation_model:MissingResolverEkfStep', ...
        'Missing resolver EKF step function: %s', resolverStepPath);
end
end

function configure_file_generation_folders(modelDirectory, modelName)
% Keep generated cache/codegen artifacts outside the repository.
fileGenerationRoot = fullfile(tempdir, [modelName '_filegen']);
cacheFolder = fullfile(fileGenerationRoot, 'cache');
codeGenFolder = fullfile(fileGenerationRoot, 'codegen');

if ~isfolder(cacheFolder)
    mkdir(cacheFolder);
end
if ~isfolder(codeGenFolder)
    mkdir(codeGenFolder);
end

if ~isfolder(modelDirectory)
    error('build_kre_ekf_validation_model:MissingModelDirectory', ...
        'Model directory does not exist: %s', modelDirectory);
end

Simulink.fileGenControl('set', ...
    'CacheFolder', cacheFolder, ...
    'CodeGenFolder', codeGenFolder, ...
    'createDir', true);
end

function configure_model(modelName)
set_param(modelName, ...
    'Solver', 'FixedStepDiscrete', ...
    'SolverType', 'Fixed-step', ...
    'FixedStep', '5e-5', ...
    'StartTime', '0.0', ...
    'StopTime', '0.2', ...
    'SaveTime', 'off', ...
    'SaveOutput', 'off', ...
    'ReturnWorkspaceOutputs', 'on', ...
    'SignalLogging', 'on', ...
    'SignalLoggingName', 'logsout', ...
    'SignalLoggingSaveFormat', 'Dataset');
end

