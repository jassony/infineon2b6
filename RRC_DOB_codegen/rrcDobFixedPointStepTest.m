classdef rrcDobFixedPointStepTest < matlab.unittest.TestCase
    %RRCDOBFIXEDPOINTSTEPTEST Integer RRC-DOB reference verification.

    properties (TestParameter)
        operatingPoint = struct( ...
            'rpm800', struct('mechanicalSpeedRpm', 800), ...
            'rpm4000', struct('mechanicalSpeedRpm', 4000))
    end

    methods (Test)
        function testConstantSpeedErrorBudget(testCase, operatingPoint)
            metrics = rrcDobFixedPointStepTest.runReplay( ...
                'constant', operatingPoint.mechanicalSpeedRpm);

            testCase.verifyLessThanOrEqual(metrics.RmsError_LSB, 2, ...
                sprintf('RMS error was %.6f Q15 LSB.', metrics.RmsError_LSB));
            testCase.verifyLessThanOrEqual(metrics.PeakError_LSB, 8, ...
                sprintf('Peak error was %.6f Q15 LSB.', metrics.PeakError_LSB));
            testCase.verifyTrue(metrics.AllStatusesValid);
            testCase.verifyEqual(metrics.ComparedSampleCount, 799);
        end

        function testSweepWithStateRescalingErrorBudget(testCase)
            metrics = rrcDobFixedPointStepTest.runReplay('sweep', 0);

            testCase.verifyLessThanOrEqual(metrics.RmsError_LSB, 2, ...
                sprintf('RMS error was %.6f Q15 LSB.', metrics.RmsError_LSB));
            testCase.verifyLessThanOrEqual(metrics.PeakError_LSB, 8, ...
                sprintf('Peak error was %.6f Q15 LSB.', metrics.PeakError_LSB));
            testCase.verifyTrue(metrics.AllStatusesValid);
            testCase.verifyEqual(metrics.ComparedSampleCount, 799);
        end

        function testExplicitFrequencyStateRescaling(testCase)
            [coefficients, qOld] = ...
                rrcDobFixedPointStepTest.identityCoefficients(single(0.10));
            [~, qNew] = ...
                rrcDobFixedPointStepTest.identityCoefficients(single(0.15));
            state = zeros(8, 1, 'int32');
            state(1:6) = rrcDobFixedPointStepTest.toQ26( ...
                [0.10; 0.20; -0.30; -0.10; -0.20; 0.30]);
            state(7:8) = [qOld; int32(1)];
            expected = rrcDobFixedPointStepTest.toQ26( ...
                [0.10; 0.45; -0.45; -0.10; -0.45; 0.45]);

            [command, estimate, stateNext, status] = rrcDobFixedPointStep( ...
                state, zeros(2, 1, 'int16'), zeros(2, 1, 'int16'), ...
                zeros(2, 1, 'int16'), coefficients, qNew, uint8(0), ...
                uint32(0), int16(32767));

            testCase.verifyEqual(stateNext(1:6), expected, ...
                'AbsTol', int32(2));
            testCase.verifyEqual(stateNext(7:8), [qNew; int32(1)], ...
                'AbsTol', int32(0));
            testCase.verifyEqual(command, zeros(2, 1, 'int16'), ...
                'AbsTol', int16(0));
            testCase.verifyEqual(estimate, zeros(2, 1, 'int16'), ...
                'AbsTol', int16(0));
            testCase.verifyEqual(status, uint8(0));
        end

        function testFirstActivationClearsUnavailableState(testCase)
            [coefficients, qCurrent] = ...
                rrcDobFixedPointStepTest.identityCoefficients(single(0.10));
            state = int32((1:8).');
            state(8) = int32(0);
            rawPi = int16([1000; -1000]);

            [command, estimate, stateNext, status] = rrcDobFixedPointStep( ...
                state, zeros(2, 1, 'int16'), zeros(2, 1, 'int16'), ...
                rawPi, coefficients, qCurrent, uint8(0), uint32(0), ...
                int16(32767));

            testCase.verifyEqual(command, rawPi, 'AbsTol', int16(0));
            testCase.verifyEqual(estimate, zeros(2, 1, 'int16'), ...
                'AbsTol', int16(0));
            testCase.verifyEqual(stateNext(1:6), zeros(6, 1, 'int32'), ...
                'AbsTol', int32(0));
            testCase.verifyEqual(stateNext(7:8), [qCurrent; int32(1)], ...
                'AbsTol', int32(0));
            testCase.verifyEqual(status, uint8(7));
        end

