        function testMacOverflowInvalidatesAndClears(testCase)
            coefficients = repmat(intmax('int32'), 19, 2);
            qCurrent = int32(round(0.1 * 2^29));
            state = repmat(intmax('int32'), 8, 1);
            state(7:8) = [qCurrent; int32(1)];
            rawPi = int16([1000; -1000]);

            [command, estimate, stateNext, status] = rrcDobFixedPointStep( ...
                state, int16([32767; 32767]), int16([32767; 32767]), ...
                rawPi, coefficients, qCurrent, uint8(0), uint32(0), ...
                int16(32767));

            testCase.verifyEqual(command, rawPi, 'AbsTol', int16(0));
            testCase.verifyEqual(estimate, zeros(2, 1, 'int16'), ...
                'AbsTol', int16(0));
            testCase.verifyEqual(stateNext, zeros(8, 1, 'int32'), ...
                'AbsTol', int32(0));
            testCase.verifyEqual(status, uint8(5));
        end

        function testCompensationLimitIsReported(testCase)
            [coefficients, qCurrent] = ...
                rrcDobFixedPointStepTest.identityCoefficients(single(0.10));
            coefficients(16, :) = int32(2^27);
            state = zeros(8, 1, 'int32');
            state(1:6) = rrcDobFixedPointStepTest.toQ26( ...
                [0.5; 0; 0; -0.5; 0; 0]);
            state(7:8) = [qCurrent; int32(1)];
            outputLimit = int16(round(0.1 * 2^15));

            [command, estimate, stateNext, status] = rrcDobFixedPointStep( ...
                state, zeros(2, 1, 'int16'), zeros(2, 1, 'int16'), ...
                int16([10000; -10000]), coefficients, qCurrent, ...
                uint8(0), uint32(2^31), outputLimit);

            testCase.verifyEqual(estimate, int16([16384; -16384]), ...
                'AbsTol', int16(0));
            testCase.verifyEqual(abs(int32(command) - int32([10000; -10000])), ...
                int32([outputLimit; outputLimit]), 'AbsTol', int32(0));
            testCase.verifyEqual(stateNext(1:6), state(1:6), ...
                'AbsTol', int32(0));
            testCase.verifyEqual(status, uint8(6));
        end

        function testApsfsmTenToOneStepErrorBudget(testCase)
