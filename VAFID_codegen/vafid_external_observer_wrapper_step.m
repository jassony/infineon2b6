function [probeD_PU, probeQ_PU, rs_Ohm, ld_H, lq_H, fluxPM_Wb, ...
    estimateValid, freshEstimate, staleEstimate, status, ...
    conditionNumber, relativeResidual, consecutiveAcceptedWindows, ...
    windowSampleCount] = vafid_external_observer_wrapper_step( ...
    mode, resetRequest, sampleValid, voltageAlpha_V, voltageBeta_V, ...
    currentAlpha_A, currentBeta_A, kreElectricalAngle_rad, ...
    kreElectricalOmega_radps, kreActiveFlux_Wb, configValues)
%VAFID_EXTERNAL_OBSERVER_WRAPPER_STEP Fixed-size ERT wrapper entry point.
%   CONFIGVALUES is a 30-by-1 single vector produced by
%   vafid_pack_wrapper_config. Keeping the model interface numeric avoids a
%   workspace-owned Simulink.Bus while preserving the reference function's
%   strongly typed configuration structure.

%#codegen

config = localUnpackConfig(configValues);
[probeD_PU, probeQ_PU, rs_Ohm, ld_H, lq_H, fluxPM_Wb, ...
    estimateValid, freshEstimate, staleEstimate, status, ...
    conditionNumber, relativeResidual, consecutiveAcceptedWindows, ...
    windowSampleCount] = vafid_discrete_reference_step( ...
    mode, resetRequest, sampleValid, voltageAlpha_V, voltageBeta_V, ...
    currentAlpha_A, currentBeta_A, kreElectricalAngle_rad, ...
    kreElectricalOmega_radps, kreActiveFlux_Wb, config);
end

function config = localUnpackConfig(values)
